// Local-only browser acceptance. The fixture is injected by Playwright and never shipped.
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {build} from 'esbuild';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
await mkdir('artifacts',{recursive:true});
const source=await readFile('src/app.js','utf8');
const fixture=await build({stdin:{contents:source+`;globalThis.__riftPlaytest={snapshot:()=>({id:run?.id,state:run?.state,time:run?.time,level:run?.level,choices:run?.rewardChoices?.length,hp:run?.player.hp,x:run?.player.x,y:run?.player.y}),level:()=>{run.xp=run.need;E.stepRun(run,{},1/60);syncState(true);}};`,resolveDir:process.cwd()+'/src',sourcefile:'app.js',loader:'js'},bundle:true,format:'esm',platform:'browser',write:false});
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{channel:'msedge'})});
 const errors=[],checks=[],layouts=[];
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/src/app.js',route=>route.fulfill({contentType:'text/javascript',body:fixture.outputFiles[0].text}));
 await page.goto('http://127.0.0.1:4173/');
 await page.locator('[data-difficulty=standard]').click();
 assert.equal(await page.locator('[data-difficulty=standard]').getAttribute('aria-pressed'),'true');
 await page.screenshot({path:'artifacts/after-home-desktop.png',fullPage:true});
 await page.locator('[data-mode=endless]').click();
 await page.locator('[data-action=launch]').dblclick();
 await page.locator('#hudHP').waitFor();
 const initial=await page.evaluate(()=>__riftPlaytest.snapshot());
 await page.waitForTimeout(1100);
 assert.equal((await page.evaluate(()=>__riftPlaytest.snapshot())).id,initial.id);
 await page.getByRole('button',{name:'Pause game',exact:true}).click();
 const paused=await page.evaluate(()=>__riftPlaytest.snapshot());
 await page.waitForTimeout(350);
 assert.equal((await page.evaluate(()=>__riftPlaytest.snapshot())).time,paused.time);
 await page.screenshot({path:'artifacts/after-pause.png'});
 await page.locator('[data-action=pause]').filter({hasText:'Resume'}).click();
 await page.waitForTimeout(100);
 await page.evaluate(()=>__riftPlaytest.level());
 await page.locator('[data-reward]').first().waitFor();
 const level=await page.evaluate(()=>__riftPlaytest.snapshot());
 await page.keyboard.press('Escape');
 assert.equal((await page.evaluate(()=>__riftPlaytest.snapshot())).state,'reward');
 await page.screenshot({path:'artifacts/after-upgrades-desktop.png'});
 await page.locator('[data-reward]').first().click();
 assert.equal((await page.evaluate(()=>__riftPlaytest.snapshot())).state,'playing');
 assert.equal((await page.evaluate(()=>__riftPlaytest.snapshot())).level,level.level);
 await page.screenshot({path:'artifacts/after-hud.png'});
 checks.push('Standard launch, duplicate start guard, frozen pause, resume, controlled level-up, Escape guard, reward selection');
 // Natural defeat: let enemies and arena hazards damage the stationary player.
 await page.waitForFunction(()=>__riftPlaytest.snapshot().state==='gameover',{},{timeout:60000});
 await page.locator('[data-action=play-again]').waitFor();
 await page.screenshot({path:'artifacts/after-results.png'});
 await page.locator('[data-action=play-again]').click();
 await page.locator('#hudHP').waitFor();
 assert.notEqual((await page.evaluate(()=>__riftPlaytest.snapshot())).id,initial.id);
 await page.getByRole('button',{name:'Pause game',exact:true}).click();
 await page.locator('[data-action=restart-run]').click();
 assert.equal(await page.locator('#dialog').evaluate(el=>el.open),true);
 await page.locator('[data-action=close-dialog]').click();
 assert.equal((await page.evaluate(()=>__riftPlaytest.snapshot())).state,'paused');
 await page.locator('[data-action=quit-run]').click();
 await page.locator('[data-action=confirm-quit]').click();
 await page.locator('[data-action=launch]').waitFor();
 assert.equal(await page.evaluate(()=>document.body.classList.contains('combat-active')),false);
 await page.locator('[data-difficulty=nightmare]').click();
 assert.equal(await page.locator('[data-difficulty=nightmare]').getAttribute('aria-pressed'),'true');
 await page.reload();
 assert.equal(await page.locator('[data-difficulty=nightmare]').getAttribute('aria-pressed'),'true');
 checks.push('Natural combat defeat, Play Again, restart cancel, confirmed quit, Nightmare saved after reload');
 for(const width of [360,390,430]){
   await page.setViewportSize({width,height:844});
   await page.locator('[data-page=expedition]').click();
   const dimensions=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,height:innerHeight,full:document.documentElement.scrollHeight}));
   assert.ok(dimensions.scroll<=width+1,`home overflow ${width}: ${dimensions.scroll}`);
   assert.ok(dimensions.full>dimensions.height,'menu should scroll');
   await page.screenshot({path:`artifacts/after-home-${width}.png`,fullPage:true});
   layouts.push(dimensions);
 }
 await page.locator('[data-action=launch]').click();await page.locator('#hudHP').waitFor();
 await page.evaluate(()=>__riftPlaytest.level());
 await page.locator('[data-reward]').first().waitFor();
 await page.screenshot({path:'artifacts/after-upgrades-mobile.png',fullPage:true});
 const cards=await page.locator('[data-reward]').evaluateAll(els=>els.map(el=>({w:el.getBoundingClientRect().width,h:el.getBoundingClientRect().height,right:el.getBoundingClientRect().right})));
 assert.ok(cards.every(c=>c.w>=44&&c.h>=44&&c.right<=431));
 await page.setViewportSize({width:844,height:390});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.screenshot({path:'artifacts/after-upgrades-landscape.png',fullPage:true});
 checks.push('360/390/430px scrollable home, touch-size upgrade targets, landscape rotation');
 // Real emulated touch input, separately from resized desktop layouts.
 const touchContext=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
 const touch=await touchContext.newPage();touch.on('pageerror',e=>errors.push(e.message));
 await touch.route('**/src/app.js',route=>route.fulfill({contentType:'text/javascript',body:fixture.outputFiles[0].text}));
 await touch.goto('http://127.0.0.1:4173/');
 await touch.locator('[data-mode=endless]').tap();await touch.locator('[data-action=launch]').tap();
 await touch.locator('#hudHP').waitFor();
 const prior=await touch.evaluate(()=>__riftPlaytest.snapshot());
 const cdp=await touchContext.newCDPSession(touch);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:65,y:680}]});
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:100,y:640}]});
 await touch.waitForTimeout(350);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 const moved=await touch.evaluate(()=>__riftPlaytest.snapshot());
 assert.ok(Math.hypot(moved.x-prior.x,moved.y-prior.y)>5,'touch stick must move the operator');
 assert.equal(await touch.evaluate(()=>scrollY),0);
 await touch.screenshot({path:'artifacts/after-touch-hud.png'});
 await touch.getByRole('button',{name:'Pause game',exact:true}).tap();
 assert.equal(await touch.locator('.touch-actions').isVisible(),false,'combat controls must not cover choices');
 await touch.locator('[data-action=game-settings]').tap();
 await touch.locator('[data-setting=reducedMotion]').check();
 await touch.locator('[data-setting=masterVolume]').focus();
 await touch.keyboard.press('Home');
 for(let i=0;i<6;i++)await touch.keyboard.press('ArrowRight');
 await touch.locator('[data-action=back-game]').tap();
 await touch.locator('[data-action=quit-run]').tap();await touch.locator('[data-action=confirm-quit]').tap();
 await touch.reload();await touch.locator('[data-page=settings]').tap();
 assert.equal(await touch.locator('[data-setting=reducedMotion]').isChecked(),true);
 assert.equal(await touch.locator('[data-setting=masterVolume]').inputValue(),'0.3');
 await touch.screenshot({path:'artifacts/after-settings-mobile.png',fullPage:true});
 checks.push('Emulated touch movement, pause hides touch controls, settings persist after reload');
 await touchContext.close();
 assert.deepEqual(errors,[]);
 await writeFile('artifacts/ui-playtest.json',JSON.stringify({checks,layouts,errors,note:'Level-up uses an injected browser-only XP fixture; game-over is a natural combat defeat.'},null,2));
 console.log(JSON.stringify({checks,layouts,errors},null,2));
}finally{await browser.close();}
